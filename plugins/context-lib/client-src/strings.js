/** 极简占位符替换：format('{a} 与 {b}', {a:1,b:2})。 */
export function format(template, vars = {}) {
  return String(template ?? '').replace(/\{(\w+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key] ?? '') : match
  ))
}
