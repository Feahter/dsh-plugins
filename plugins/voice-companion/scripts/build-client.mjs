// Bundles src/client/*.js into client.js in the ModuleLoader factory form the Host serves.
// Order matters: helpers first, avatar, audio engine, then the orchestration entry.
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PARTS = [
  'characters.js',
  'avatar.js',
  'audio.js',
  'polish.js',
  'dictation.js',
  'hotkey.js',
  'index.js',
];

/**
 * Every part is authored as its own ESM module so node tests can import it directly;
 * the bundle is one function body, so the import statements are dropped and the
 * exported declarations are inlined. `export const __test` becomes a plain const.
 */
function flatten(source) {
  return source
    .replace(/^import\s[^;]*?from\s*'[^']*';?\s*$/gm, '')
    .replace(/^export\s+(default\s+)?(async\s+function|function|const|let|var|class)/gm, '$2')
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, '')
    .replace(/^export\s+default\s+/gm, '');
}

const override = process.env.AVATAR_OVERRIDE;
const parts = [];
for (const name of PARTS) {
  const path = name === 'avatar.js' && override
    ? override
    : join(root, 'src', 'client', name);
  const source = await readFile(path, 'utf8');
  const body = flatten(source);
  parts.push(`// ---- src/client/${name} ----\n${body.trim()}\n`);
}

const bundle = `// Generated by scripts/build-client.mjs — do not edit by hand.
// Source lives in src/client/*.js.
window.__ModuleLoader__.load({
  id: 'dsh-voice-companion',
  factory(require) {
    'use strict';
${parts.join('\n')}
    return voiceCompanion;
  },
});
`;

await writeFile(join(root, 'client.js'), bundle);
console.log('client.js', bundle.length, 'bytes from', PARTS.join(', '));
