// Serialize the runtime mascot art into the two static files the repo publishes:
//   assets/fish.svg — canonical 240x200 whale mark (same markup the panel mounts)
//   icon.svg        — 64x64 market icon derived from the same paths
// Run after changing src/client/characters.js: `node scripts/make-icon.mjs`.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { renderCharacter } from '../src/client/characters.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

function makeNode(tag) {
  return {
    tag,
    attrs: {},
    children: [],
    setAttribute(name, value) { this.attrs[name] = String(value); },
    getAttribute(name) { return this.attrs[name]; },
    appendChild(child) { this.children.push(child); return child; },
  };
}
const doc = { createElementNS: (ns, tag) => makeNode(tag) };

function findAll(node, pred, out = []) {
  if (pred(node)) out.push(node);
  for (const kid of node.children) findAll(kid, pred, out);
  return out;
}

function serialize(node) {
  const attrs = Object.keys(node.attrs).map((k) => ` ${k}="${node.attrs[k]}"`).join('');
  if (!node.children.length) return `<${node.tag}${attrs}/>`;
  return `<${node.tag}${attrs}>${node.children.map(serialize).join('')}</${node.tag}>`;
}

const whale = renderCharacter(doc, 'whale').svg;
// The builder emits one scaled group holding [body, belly]; grab those two paths.
const scaleGroup = findAll(whale, (n) => typeof n.attrs.transform === 'string' && n.attrs.transform.includes('scale(4.2)'))[0];
const bodyD = scaleGroup.children[0].attrs.d;
const bellyD = scaleGroup.children[1].attrs.d;

// 1. Canonical art: the mounted markup, plus a width/height so it opens standalone.
const fish = `<!-- Generated by scripts/make-icon.mjs from renderCharacter('whale') in
     src/client/characters.js. Edit the builder there, then rerun the script. -->
${serialize(whale).replace('<svg ', '<svg width="240" height="200" aria-label="DeepSeek 鲸鱼管家" ')}`;
writeFileSync(join(ROOT, 'assets/fish.svg'), fish + '\n');

// 2. Market icon: the mascot silhouette on the plugin's accent gradient. The two
// paths are the 50-unit source art (translate(15 0) scale(4.2) is baked in by the
// panel), so the group below re-applies only the icon's own shutter.
const icon = `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64" role="img" aria-label="Voice companion">
  <defs>
    <linearGradient id="vc-icon-bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#6B85FF"/>
      <stop offset="1" stop-color="#3B47C8"/>
    </linearGradient>
  </defs>
  <rect x="1" y="1" width="62" height="62" rx="15" fill="url(#vc-icon-bg)"/>
  <g transform="translate(5.6 9.9) scale(0.2178)">
    <g transform="translate(15 0) scale(4.2)">
      <path d="${bodyD}" fill="#FFFFFF"/>
      <path d="${bellyD}" fill="#C3CFFF"/>
    </g>
  </g>
  <circle cx="19.5" cy="25.1" r="3.6" fill="#16204A"/>
  <circle cx="18.4" cy="23.9" r="1.2" fill="#FFFFFF" opacity="0.9"/>
</svg>
`;
writeFileSync(join(ROOT, 'icon.svg'), icon);

console.log('assets/fish.svg', fish.length + 1, 'bytes · icon.svg', icon.length, 'bytes');
console.log('whale-body path', bodyD.length, 'chars · whale-belly path', bellyD.length, 'chars');
