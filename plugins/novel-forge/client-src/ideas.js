const GENRE_POOL = Object.keys(PREMISES)
const pick = list => list[Math.floor(Math.random() * list.length)]

/** 随机拼一套可用的新建参数；章节数偏向网文常见的长篇幅。 */
export function randomIdea() {
  const genre = pick(GENRE_POOL)
  const chapters = pick([100, 200, 300, 600, 1000])
  return {
    premise: pick(PREMISES[genre]),
    title: pick(TITLES[genre] || TITLES.通用),
    genre,
    tone: pick(TONES),
    chapters,
    wordsPerChapter: pick([2000, 2500, 3000, 3500]),
  }
}
