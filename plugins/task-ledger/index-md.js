/**
 * Generated ledger index. Two audiences:
 * - a human (or a different agent) who opened the directory and wants to know
 *   what lives here without reading every task;
 * - a model that starts in a fresh session and must find the right task before
 *   planning (the "four questions" page below).
 *
 * The index is regenerated after every accepted write. It is derived state:
 * deleting it loses nothing, and it is never read back as canonical.
 */

import { promises as fs } from 'node:fs';
import path from 'node:path';

const FOUR_QUESTIONS = [
  ['这是什么', '一个以任务为中心的账本（task ledger）：每个任务一个目录，会话只是任务的一次 run。'],
  ['任务在哪', '`tasks/<task-id>/`：`task.json` 章程、`state.json` 现值、`claims.jsonl` 证据主张、`decisions.jsonl` 决策、`runs/` 交接报告、`evidence/` 原文快照。'],
  ['怎么恢复', '新会话只给 `task_id`，调用 `task_resume`；它会读回状态、签发本轮 run_id 并注入续跑摘要。不要从聊天记录里重建。'],
  ['谁在写', '`state.json` 的 `lease` 与 `active.json` 指出当前 canonical writer；写入必须持有租约，一次只能有一个 run 写。'],
];

function cell(value) {
  return String(value === null || value === undefined ? '' : value).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

export async function regenerateIndex(root, config = {}) {
  const { listTasks, getActiveTaskId, nowIso } = await import('./ledger.js');
  const { tasks } = await listTasks(root, { status: 'all', limit: 500 });
  const activeTaskId = await getActiveTaskId(root).catch(() => null);
  const counts = { open: 0, blocked: 0, done: 0, archived: 0 };
  for (const task of tasks) {
    if (Object.hasOwn(counts, task.status)) counts[task.status] += 1;
  }
  const active = tasks.find((task) => task.task_id === activeTaskId) || null;

  const lines = [];
  lines.push('# Task ledger');
  lines.push('');
  lines.push(`Generated by \`dsh-task-ledger\` at ${nowIso()}. Derived file — safe to delete, regenerated on every write.`);
  lines.push('');
  lines.push(`Root: \`${root}\``);
  lines.push('');
  lines.push('## Four questions');
  lines.push('');
  lines.push('| Question | Answer |');
  lines.push('| --- | --- |');
  for (const [question, answer] of FOUR_QUESTIONS) {
    lines.push(`| ${cell(question)} | ${cell(answer)} |`);
  }
  lines.push('');
  lines.push('## Counts');
  lines.push('');
  lines.push(`open ${counts.open} · blocked ${counts.blocked} · done ${counts.done} · archived ${counts.archived} · total ${tasks.length}`);
  lines.push('');
  if (active) {
    lines.push('## Active task');
    lines.push('');
    lines.push(`\`${active.task_id}\` — ${active.title}`);
    lines.push('');
    if (active.next_actions.length) {
      lines.push('Next actions:');
      lines.push('');
      for (const action of active.next_actions) lines.push(`- [ ] ${action}`);
      lines.push('');
    }
    if (active.blocked_reason) {
      lines.push(`Blocked: ${active.blocked_reason}`);
      lines.push('');
    }
  }
  lines.push('## Tasks');
  lines.push('');
  if (!tasks.length) {
    lines.push('No tasks yet. Create one with `task_open`.');
    lines.push('');
  } else {
    lines.push('| task_id | title | status | phase | claims | evidence | next action | updated |');
    lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const task of tasks) {
      const next = task.next_actions.length ? task.next_actions[0] : '';
      lines.push(
        `| \`${cell(task.task_id)}\` | ${cell(task.title)} | ${cell(task.status)} | ${cell(task.phase)} | ${task.claim_count} | ${task.evidence_count} | ${cell(next)} | ${cell(task.updated_at)} |`,
      );
    }
    lines.push('');
  }
  lines.push('## Layout');
  lines.push('');
  lines.push('```');
  lines.push('tasks/<task-id>/');
  lines.push('  task.json          immutable charter: goal, questions, acceptance, evidence bar, budget');
  lines.push('  state.json         mutable: phase, status, open_questions, next_actions, lease, version');
  lines.push('  claims.jsonl       append-only claims; latest record per id wins (refutations are kept)');
  lines.push('  decisions.jsonl    append-only decisions with rejected options and evidence grade');
  lines.push('  evidence/          content-addressed snapshots + index.jsonl (url, sha256, fetched_at)');
  lines.push('  runs/<run-id>.md   handoff report: what happened, what failed, what is next');
  lines.push('  artifacts/         outlines, drafts, final reports');
  lines.push('audit.jsonl          plugin-level write/failure audit trail');
  lines.push('active.json          pinned task for session-start injection');
  lines.push('```');
  lines.push('');
  lines.push('## Contract');
  lines.push('');
  lines.push('- One canonical writer per task: `task_resume` leases the task and returns a `run_id`; every write must carry it.');
  lines.push('- `state.version` is an optimistic lock; pass `expected_version` when a stale read would be dangerous.');
  lines.push('- Closeout is mandatory: `task_close` writes a run report and applies the evidence gate before marking done.');
  lines.push('');
  await fs.mkdir(root, { recursive: true });
  const file = path.join(root, 'INDEX.md');
  const text = lines.join('\n');
  const tmp = `${file}.tmp-${process.pid}`;
  await fs.writeFile(tmp, text, 'utf8');
  await fs.rename(tmp, file);
  return { file, tasks: tasks.length, counts };
}
